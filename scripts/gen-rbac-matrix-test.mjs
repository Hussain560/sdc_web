// Generates supabase/tests/03_rbac_matrix.sql from the role × permission matrix of
// docs/06-security/permission-catalog.md §2. Run: node scripts/gen-rbac-matrix-test.mjs
// The expectations are written independently of the seed migration so drift between the
// documented matrix and the database fails the pgTAP suite.
import { writeFileSync } from 'node:fs';

import { GRANTS, PERMISSIONS } from '../tests/fixtures/rbac-matrix.mjs';

const GLOBAL = new Set(['system_admin', 'community_leader', 'founder', 'advisor']);
const roles = Object.keys(GRANTS);
const uuid = (n) => `00000000-0000-0000-0000-${String(n).padStart(12, '0')}`;
const idOf = (role) => uuid(0xa000 + roles.indexOf(role));

const lines = [];
const out = (s = '') => lines.push(s);
let tests = 0;

out('-- GENERATED by scripts/gen-rbac-matrix-test.mjs — do not edit by hand.');
out('-- Sprint 04 · ACC-001: the full role × permission matrix against private.has_permission().');
out('begin;');
out('-- isolate from dev personas / E2E leftovers: this transaction is rolled back');
out('delete from public.role_assignments;');
out('select plan(__PLAN__);');
out();
out(
  "create temp table _c as select (select id from public.committees where slug = 'ai') as a, (select id from public.committees where slug = 'cybersecurity') as b;",
);
out('grant select on _c to authenticated;');
out();
for (const role of roles) {
  out(
    `insert into auth.users (id, aud, role, email, raw_user_meta_data) values ('${idOf(role)}', 'authenticated', 'authenticated', '${role}@example.test', '{"full_name":"Persona ${role}"}');`,
  );
}
out();
out(
  '-- assignments are inserted directly (as the table owner); the functions are tested in 04_role_assignments.sql',
);
for (const role of roles) {
  if (role === 'plain_user') continue;
  if (GLOBAL.has(role)) {
    out(
      `insert into public.role_assignments (user_id, role_key) values ('${idOf(role)}', '${role}');`,
    );
  } else {
    out(
      `insert into public.role_assignments (user_id, role_key, committee_id) select '${idOf(role)}', '${role}', a from _c;`,
    );
  }
}
out();
out('set local role authenticated;');

for (const role of roles) {
  out();
  out(
    `select set_config('request.jwt.claims', '{"sub":"${idOf(role)}","role":"authenticated"}', true);`,
  );
  for (const perm of PERMISSIONS) {
    const granted = GRANTS[role].includes(perm);
    if (GLOBAL.has(role) || role === 'plain_user') {
      const want = granted;
      out(
        `select is(private.has_permission('${perm}'), ${want}, '${role} · ${perm} (no scope) = ${want}');`,
      );
      tests++;
      out(
        `select is(private.has_permission('${perm}', (select b from _c)), ${want}, '${role} · ${perm} (any committee) = ${want}');`,
      );
      tests++;
    } else {
      // committee-scoped roles hold the permission only in their own committee (a), never in b or without scope
      out(
        `select is(private.has_permission('${perm}', (select a from _c)), ${granted}, '${role} · ${perm} in own committee = ${granted}');`,
      );
      tests++;
      out(
        `select is(private.has_permission('${perm}', (select b from _c)), false, '${role} · ${perm} in another committee = false');`,
      );
      tests++;
      out(
        `select is(private.has_permission('${perm}'), false, '${role} · ${perm} without scope = false');`,
      );
      tests++;
    }
  }
}

out();
out('reset role;');
out('select * from finish();');
out('rollback;');

writeFileSync(
  new URL('../supabase/tests/03_rbac_matrix.sql', import.meta.url),
  lines.join('\n').replace('__PLAN__', String(tests)) + '\n',
);
console.log(`wrote 03_rbac_matrix.sql with ${tests} assertions`);
