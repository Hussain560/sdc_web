// One-off generator for supabase/migrations/20270131000100_legacy_articles.sql (Sprint 09 · ART-003).
// Reads the six hardcoded articles from the OLD detail page (app/[locale]/articles/[id]/page.tsx, taken from git
// history) and writes an idempotent migration keyed by legacy_id. It is kept for audit only: once the migration
// ships, the hardcoded data no longer exists in the code base.
//   node scripts/gen-legacy-articles.mjs <path-to-old-detail-page.tsx>
import { readFileSync, writeFileSync } from 'node:fs';

const [detailPath] = process.argv.slice(2);
const src = readFileSync(detailPath, 'utf8');

const start = src.indexOf('const articlesDatabase: Record<string, ArticleRecord> = {');
const open = src.indexOf('{', start + 'const articlesDatabase'.length);
const end = src.indexOf('\n};', open);
const articles = Function(`"use strict"; return (${src.slice(open, end + 2)})`)();

// Slugs and publish dates were free text on the old pages; they are mapped by hand.
const META = {
  1: { slug: 'prompt-engineering', date: '2024-08-15' },
  2: { slug: 'voice2face', date: '2024-11-25' },
  3: { slug: 'recommendation-systems', date: '2025-09-12' },
  4: { slug: 'chinese-and-english-applications', date: '2023-06-11' },
  5: { slug: 'ai-in-games-and-reinforcement-learning', date: '2025-10-17' },
  6: { slug: 'ai-sentiment-analysis', date: '2025-09-26' },
};

const q = (v) => (v == null ? 'null' : `$sdc$${String(v)}$sdc$`);
const slugify = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
const excerpt = (text) => {
  const first = text.split(/\n{2,}/)[0].trim();
  return first.length > 300 ? `${first.slice(0, 297).trimEnd()}…` : first;
};
const COMMITTEE_AR = 'لجنة الذكاء الاصطناعي';

const out = [];
out.push(`-- Sprint 09 · ART-003 — the six existing articles as rows (idempotent, keyed by legacy_id).
-- GENERATED by scripts/gen-legacy-articles.mjs from the old hardcoded detail page. Reading time is recomputed by
-- the table trigger, so the typed "3 min" values are gone. Authors: committee byline or guest names; tags paired
-- by position from the old Arabic/English lists.
`);

const tagRows = new Map();
const lines = [];
for (const [id, a] of Object.entries(articles)) {
  const m = META[id];
  const aiCommittee = a.author.ar === COMMITTEE_AR;
  const arTags = a.tags.ar.map((t) => t.trim());
  const enTags = a.tags.en.map((t) => t.trim());
  const seen = new Set();
  const tags = [];
  arTags.forEach((labelAr, i) => {
    const labelEn = enTags[i] ?? null;
    const slug = slugify(labelEn || labelAr) || `tag-${i}`;
    if (seen.has(slug)) return;
    seen.add(slug);
    tags.push({ slug, labelAr, labelEn });
    if (!tagRows.has(slug)) tagRows.set(slug, { slug, labelAr, labelEn });
  });

  lines.push(`-- legacy article ${id}: ${a.title.en}`);
  lines.push(`insert into public.articles (legacy_id, slug, committee_id, status, title_ar, title_en, excerpt_ar, excerpt_en,
  body_ar, body_en, resource_url, resource_label_ar, resource_label_en, published_at, created_at)
select ${id}, ${q(m.slug)}, (select id from public.committees where slug = 'ai'), 'published',
  ${q(a.title.ar)}, ${q(a.title.en)}, ${q(excerpt(a.content.ar))}, ${q(excerpt(a.content.en))},
  ${q(a.content.ar)}, ${q(a.content.en)},
  ${q(a.sourceLink ?? null)}, ${q(a.sourceLabel?.ar ?? null)}, ${q(a.sourceLabel?.en ?? null)},
  '${m.date} 09:00:00+03'::timestamptz, '${m.date} 09:00:00+03'::timestamptz
where not exists (select 1 from public.articles where legacy_id = ${id});
`);

  if (aiCommittee) {
    lines.push(`insert into public.article_authors (article_id, position, committee_id, display_name_ar, display_name_en)
select a.id, 0, (select id from public.committees where slug = 'ai'), ${q(a.author.ar)}, ${q(a.author.en)}
from public.articles a where a.legacy_id = ${id}
on conflict (article_id, position) do nothing;
`);
  } else {
    const namesAr = a.author.ar.split('–').map((s) => s.trim());
    const namesEn = a.author.en.split('–').map((s) => s.trim());
    namesAr.forEach((nameAr, i) => {
      lines.push(`insert into public.article_authors (article_id, position, display_name_ar, display_name_en)
select a.id, ${i}, ${q(nameAr)}, ${q(namesEn[i] ?? null)} from public.articles a where a.legacy_id = ${id}
on conflict (article_id, position) do nothing;
`);
    });
  }

  tags.forEach((t, position) => {
    lines.push(`insert into public.article_tags (article_id, tag_id, position)
select a.id, t.id, ${position} from public.articles a, public.tags t where a.legacy_id = ${id} and t.slug = ${q(t.slug)}
on conflict do nothing;
`);
  });
}

out.push('-- tags');
for (const t of tagRows.values()) {
  out.push(
    `insert into public.tags (slug, label_ar, label_en) values (${q(t.slug)}, ${q(t.labelAr)}, ${q(t.labelEn)}) on conflict (slug) do nothing;`,
  );
}
out.push('');
out.push(...lines);

writeFileSync(
  new URL('../supabase/migrations/20270131000100_legacy_articles.sql', import.meta.url),
  out.join('\n'),
);
console.log(`wrote ${Object.keys(articles).length} articles, ${tagRows.size} tags`);
