// One-off generator for supabase/migrations/20261220000000_legacy_events.sql (Sprint 06 · EVT-005).
// Reads the six hardcoded events from the OLD pages (src/data/allEvents.ts and the eventsDatabase object of the
// old event detail page, taken from git history) and writes an idempotent migration. It is kept for audit only:
// after the migration ships, the hardcoded data no longer exists in the code base.
//   node scripts/gen-legacy-events.mjs <path-to-old-detail-page.tsx> <path-to-old-allEvents.ts>
import { readFileSync, writeFileSync } from 'node:fs';

const [detailPath, listPath] = process.argv.slice(2);
const detail = readFileSync(detailPath, 'utf8');
const list = readFileSync(listPath, 'utf8');

const grab = (src, start, end) => {
  const i = src.indexOf(start) + start.length - 1; // at the opening brace/bracket
  const j = src.indexOf(end, i);
  return Function(`"use strict"; return (${src.slice(i, j + 2)})`)();
};
const events = grab(detail, 'const eventsDatabase: Record<string, EventRecord> = {', '\n};');
const summaries = grab(list, 'export const allEventsData: LegacyEventSummary[] = [', '\n];');

// Dates were free text; they are mapped by hand (docs/01-project/current-system-audit.md §legacy events).
const META = {
  1: {
    slug: 'github-basics-meetup',
    type: 'meetup',
    start: null,
    end: null,
    schedule: 'single_day',
  },
  2: {
    slug: 'google-ai-studio-workshop',
    type: 'workshop',
    start: '2026-08-05',
    end: null,
    schedule: 'single_day',
  },
  3: {
    slug: 'excel-power-bi-workshop',
    type: 'workshop',
    start: '2025-09-20',
    end: null,
    schedule: 'single_day',
  },
  4: {
    slug: 'cybersecurity-fundamentals-camp',
    type: 'bootcamp',
    start: '2024-09-15',
    end: '2024-09-19',
    schedule: 'consecutive_range',
  },
  5: {
    slug: 'ctf-fundamentals-camp',
    type: 'bootcamp',
    start: '2024-10-27',
    end: '2024-11-01',
    schedule: 'consecutive_range',
  },
  6: {
    slug: 'huawei-startapps-camp',
    type: 'bootcamp',
    start: '2023-03-02',
    end: null,
    schedule: 'single_day',
  },
};

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const arr = (l) => ({ ar: l.ar ?? [], en: l.en ?? [] });

const rows = Object.entries(events).map(([id, e]) => {
  const m = META[id];
  const s = summaries.find((x) => String(x.id) === id);
  const certificate = /شهادة حضور/.test(e.prizes.ar) && !/لا توجد/.test(e.prizes.ar);
  const faq = e.faq.ar.map((a, i) => ({ q_ar: '', q_en: '', a_ar: a, a_en: e.faq.en[i] ?? a }));
  const details = {
    target_audience: { ar: [e.target.ar], en: [e.target.en] },
    requirements: arr(e.requirements),
    responsibilities: arr(e.responsibilities),
    deliverables: arr(e.deliverables),
    benefits: arr(e.benefits),
  };
  const published = m.start ?? '2026-01-01';
  return `insert into public.events (
    legacy_id, slug, committee_id, type, status, title_ar, title_en, schedule_type, start_date, end_date,
    location_mode, location_ar, location_en, goals, faq, details, display_config, cover_image_path,
    awards_ar, awards_en, certificate_available, contact_email, published_at
  ) values (
    ${id}, ${q(m.slug)}, (select id from public.committees where slug = 'tech-development'), ${q(m.type)}, 'published',
    ${q(e.title.ar)}, ${q(e.title.en)}, ${q(m.schedule)}, ${q(m.start)}, ${q(m.end)},
    'online', ${q(e.location.ar)}, ${q(e.location.en)}, '{"ar":[],"en":[]}'::jsonb, ${json(faq)}, ${json(details)},
    '{"show_presenters":false,"show_goals":false,"show_faq":true,"show_seats_remaining":false,"auto_close_registration":true,"show_details":true}'::jsonb,
    ${q(s.image)}, ${q(e.prizes.ar)}, ${q(e.prizes.en)}, ${certificate}, ${q(e.email)}, ${q(published + 'T00:00:00+03:00')}
  ) on conflict (legacy_id) do nothing;`;
});

const sql = `-- Sprint 06 · EVT-005 — the six hardcoded events become rows (idempotent; legacy_id is the key).
-- GENERATED by scripts/gen-legacy-events.mjs from the old pages. Registrations are mapped to these rows by legacy_id.
-- Cover images are the existing static assets (paths starting with "/"); new covers live in the public-media bucket.

${rows.join('\n\n')}

insert into public.event_private_details (event_id)
select id from public.events where legacy_id is not null
on conflict (event_id) do nothing;
`;
writeFileSync(
  new URL('../supabase/migrations/20261220000000_legacy_events.sql', import.meta.url),
  sql,
);
console.log(`wrote ${rows.length} events`);
